"""Generate src/gxw3call/api.py: one Python method per COM method.

usage: gen_api.py [tlb dump] [out.py]

Every method of every interface becomes a thin wrapper over Gx.call().
Method, parameter and output names are snake_case with the Hungarian prefix
dropped (bstrProjectPath -> project_path, lpdwError -> error). The return
value is the dict of output parameters plus 'hresult'; struct fields inside
it are renamed the same way.

Signatures come straight from the type library and say nothing about what
an argument means. Methods listed in notes/measured.json get that note as
their docstring; all others are marked as not measured.
"""

import json
import os
import sys

from gxw3call import typelib
from gxw3call.client import DEFAULT_TLB
from gxw3call.naming import python_names, snake

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTES = os.path.join(REPO, 'notes', 'measured.json')

HEADER = '''"""GXW3Call methods as Python methods. GENERATED by gen_api.py.

    api = Api(gx)
    out = api.project.get_plc_type_string(call_id)
    out['plc_type_string'], out['return_code'], out['hresult']

Signatures only: the vendor does not document argument meanings or return
codes. A docstring that starts with "Measured" records what real calls
showed (notes/measured.json): "works", "fails" with the arguments tried, or
"unclear". "Not measured" means only the signature is known. Names are
snake_case with the Hungarian prefix dropped; each
docstring lists the type library name next to it. Bytes (call ids, raw
structs) are hex strings. alloc/count are passed to Gx.call for outputs
whose size the callee does not report and use type library names.
"""

from gxw3call.naming import convert_keys


class _Interface:
    NAME = ''

    def __init__(self, gx):
        self._gx = gx

    def _call(self, method, alloc, count, **args):
        hresult, out = self._gx.call(
            self.NAME, method, alloc=alloc, count=count, **args
        )
        out = convert_keys(out)
        out['hresult'] = hresult
        return out
'''


def status_line(entry):
    """notes/measured.json entry -> first docstring line."""
    if not entry:
        return 'Not measured.'
    note = entry['note'].replace('\\', '/').replace('"""', "'")
    return f'Measured, {entry["status"]}.' + (f' {note}' if note else '')


def render_method(method, entry):
    ins = [
        p
        for p in method.params
        if p.direction != 'out' and p.type != 'IUnknown*'
    ]
    outs = [p for p in method.params if p.direction != 'in']
    in_names = python_names([p.name for p in ins])
    out_names = python_names([p.name for p in outs])
    required = [p for p in ins if p.direction == 'in']
    optional = [p for p in ins if p.direction != 'in']
    sig = ''.join(f', {in_names[p.name]}' for p in required)
    sig += ''.join(f', {in_names[p.name]}=None' for p in optional)
    status = status_line(entry)
    name = snake(method.name)
    lines = [
        f'    def {name}(self{sig}, *, alloc=None, count=None):',
        f'        """{status}',
        '',
        f'        {method.name}, vtable {method.vtbl}.',
    ]
    for p in ins:
        lines.append(f'        in  {in_names[p.name]}: {p.type} {p.name}')
    for p in outs:
        lines.append(f'        out {out_names[p.name]}: {p.type} {p.name}')
    lines.append('        """')
    args = ''.join(f', {p.name}={in_names[p.name]}' for p in ins)
    lines.append(
        f"        return self._call('{method.name}', alloc, count{args})"
    )
    return '\n'.join(lines)


def class_name(iface_name):
    return iface_name[len('IGXW3Call') :]  # IGXW3CallProject -> Project


def render(tlb, notes):
    out = [HEADER]
    members = []
    for iface in tlb.interfaces.values():
        if not iface.clsid or not iface.name.startswith('IGXW3Call'):
            continue
        cls = class_name(iface.name)
        members.append(cls)
        out.append(f'\n\nclass {cls}(_Interface):')
        out.append(f"    NAME = '{iface.name}'")
        seen = set()
        for method in iface.methods.values():
            name = snake(method.name)
            assert name not in seen, f'{cls}.{name} is not unique'
            seen.add(name)
            out.append('')
            out.append(render_method(method, notes.get(method.name)))
    out.append('\n\nclass Api:')
    out.append('    """All interfaces of one Gx connection."""\n')
    out.append('    def __init__(self, gx):')
    for cls in members:
        out.append(f'        self.{cls.lower()} = {cls}(gx)')
    return '\n'.join(out) + '\n'


def main(argv):
    tlb = typelib.load(argv[1] if len(argv) > 1 else DEFAULT_TLB)
    path = (
        argv[2]
        if len(argv) > 2
        else os.path.join(REPO, 'src', 'gxw3call', 'api.py')
    )
    with open(NOTES, encoding='utf-8') as f:
        notes = json.load(f)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(tlb, notes))
    methods = [
        m
        for i in tlb.interfaces.values()
        if i.clsid and i.name.startswith('IGXW3Call')
        for m in i.methods
    ]
    measured = sum(1 for m in methods if m in notes)
    print(f'{path}: {len(methods)} methods, {measured} with a measured note')


if __name__ == '__main__':
    main(sys.argv)
